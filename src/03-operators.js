// Operadores aritméticos

// SUMA (+)

const suma = 5 + 3;
console.log(suma);

// RESTA (-)

const resta = 5 - 3;
console.log(resta);

// MULTIPLICACIÓN (*)

const multiplicacion = 5 * 3;
console.log(multiplicacion);

// DIVISION (/)

const division = 6 / 3;
console.log(division);

// MODULO (%)

const modulo = 5 % 2;
console.log(modulo);

// POTENCIACIÓN (**)

const potencia = 2 ** 3;
console.log(potencia);

// Operadores de asignación

// Asignación con SUMA (+=)
let a = 5;
a += 3;
console.log(a);

// Asignación con RESTA (-=)
let b = 10;
b -= 5;
console.log(b);

// Asignación con MULTIPLICACIÓN (*=)
let c = 6;
c *= 2;
console.log(c);

// Asignación con DIVISIÓN (/=)
let d = 15;
d /= 3;
console.log(d);

// Operadores de INCREMENTO Y DECREMENTO
let contador = 10;

contador ++; // Incremento en 1
console.log(contador);

contador--; // Decremento en 1
console.log(contador);

// INFINITY

console.log(1/0);
console.log(-1/0);

// NaN

console.log(0/0);
console.log("hola" * 2);