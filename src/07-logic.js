// Operadores Lógicos

// AND (&&) OR (||) NOT (!)

// Operador AND (&&)
// Devuelve true solo si ambas expresiones son verdaderas

console.log(true && true); // Devuelve true
console.log(true && false); //Devuelve false
console.log(false && true); //Devuelve false

// Operador OR (||)
// Devuelve true si al menos una expresion es verdadera

console.log(true || true);
console.log(true || false);
console.log(false || false);

// Operador NOT (!)
console.log(!true);
console.log(!false);